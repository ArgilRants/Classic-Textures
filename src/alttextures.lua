-- Take ownership of sinful Jokers for border config options
SMODS.Joker:take_ownership('lusty_joker', {
    pos = { x = 0, y = 0 },
    set_sprites = function(self, card, front)
        if ctex.is_pack_active("texpack_ctex_changedsprites") then
            if mod.config.bordered_sin_jokers == true then
                card.children.center.atlas.name = "ctex_lusty_bordered"
                card.children.center:reset()
            else
                card.children.center.atlas.name = "ctex_lusty"
                card.children.center:reset()
            end
        else
            card.children.center.atlas.name = "ctex_default_lusty"
            card.children.center:reset()
        end
    end,
    update = function(self, card, dt)
        if ctex.is_pack_active("texpack_ctex_changedsprites") then
            if mod.config.bordered_sin_jokers == true then
                card.children.center.atlas.name = "ctex_lusty_bordered"
                card.children.center:reset()
            else
                card.children.center.atlas.name = "ctex_lusty"
                card.children.center:reset()
            end
        else
            card.children.center.atlas.name = "ctex_default_lusty"
            card.children.center:reset()
        end
    end
},true)

